"""Tournament record shapes.

A verdict record carries two zones inside Bloberia's application-owned ``value``:
an engine-written ``envelope`` and an opaque consumer ``slot``. Bloberia's own
reserved envelope (``id``/``created_at``/``updated_at``/``revision``) cannot hold
engine fields, so this split lives one level down.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum


RECORD_KIND_TOURNAMENT = "tournament"
RECORD_KIND_VERDICT = "verdict"

ENVELOPE_KEY = "envelope"
SLOT_KEY = "slot"
KIND_KEY = "kind"

ENVELOPE_FIELDS = frozenset(
    {
        "tournament_id",
        "match_id",
        "players",
        "presented",
        "outcome",
        "ordering",
        "controls",
        "player_labels",
        "match_label",
        "template",
        "template_bindings",
        "ticket",
        "refusal_reason",
        "judge",
        "verbatim_hash",
        "recorded_at",
        "duration_ms",
    }
)


class TournamentError(RuntimeError):
    pass


class MatchIdentityRequiredError(TournamentError):
    """The consumer supplied no match identity.

    The engine requires one and never computes a default: a generated identity
    would make every match a singleton and silently stop accumulation.
    """


class EnvelopeShadowedError(TournamentError):
    """The consumer slot restated a field the engine envelope owns."""


class VerdictOutcome(str, Enum):
    ORDERED = "ordered"
    NO_CONTEST = "no_contest"


@dataclass(frozen=True)
class Tournament:
    """A definition reference and the namespace its records accumulate in.

    It carries no player pool: the engine holds none, and a fold enumerates its
    players from the verdicts themselves.
    """

    tournament_id: str
    definition_path: str
    definition_digest: str
    created_at: str


@dataclass(frozen=True)
class Verdict:
    """One completed match's recorded outcome."""

    record_id: str
    envelope: dict[str, object]
    slot: dict[str, object]

    @property
    def match_id(self) -> str:
        return str(self.envelope["match_id"])

    @property
    def outcome(self) -> str:
        return str(self.envelope["outcome"])

    @property
    def ordering(self) -> tuple[str, ...] | None:
        """The match's players best first, or None for a no-contest.

        There is no single-winner accessor: at N>2 "the winner" is the least
        interesting thing the record knows, and pairwise comparisons are a
        read-side fold over this ordering.
        """
        value = self.envelope.get("ordering")
        if value is None:
            return None
        return tuple(str(item) for item in value)


def require_match_id(match_id: str) -> str:
    if not isinstance(match_id, str) or not match_id.strip():
        raise MatchIdentityRequiredError(
            "a match identity is required and is never generated by the engine; "
            "supply one from the tournament definition's identity hook"
        )
    return match_id


def require_unshadowed_slot(slot: object) -> dict[str, object]:
    if slot is None:
        return {}
    if not isinstance(slot, dict):
        raise TournamentError("the consumer slot must be a JSON object")
    shadowed = sorted(ENVELOPE_FIELDS.intersection(slot))
    if shadowed:
        raise EnvelopeShadowedError(
            "the consumer slot may not restate engine envelope fields: "
            + ", ".join(shadowed)
        )
    return dict(slot)
